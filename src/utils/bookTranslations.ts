/**
 * Normalizes a version ID or language code to a 2-letter language code
 */
export function getLanguageCode(versionIdOrLang?: string): string {
  if (!versionIdOrLang) return 'en';
  const val = versionIdOrLang.toLowerCase();
  // If it's a 2-letter language code, return it
  if (val.length === 2) return val;
  // Otherwise, map via VERSION_TO_LANG, or default to 'en'
  return VERSION_TO_LANG[val] || 'en';
}

/**
 * Retrieve the translated book name
 * @param bookNumber - Book number (1-66)
 * @param versionIdOrLang - Active Bible version ID (e.g., 'rvr', 'kor') or language code (e.g., 'es', 'ko')
 */
export function getBookName(bookNumber: number, versionIdOrLang?: string): string {
  const lang = getLanguageCode(versionIdOrLang);
  if (lang !== 'en' && BOOK_TRANSLATIONS[lang] && BOOK_TRANSLATIONS[lang][bookNumber]) {
    return BOOK_TRANSLATIONS[lang][bookNumber];
  }
  return BOOK_NAMES[bookNumber] || `Book ${bookNumber}`;
}

/**
 * Retrieve the translated book abbreviation
 * @param bookNumber - Book number (1-66)
 * @param versionIdOrLang - Active Bible version ID (e.g., 'rvr', 'kor') or language code (e.g., 'es', 'ko')
 */
export function getBookAbbreviation(bookNumber: number, versionIdOrLang?: string): string {
  const lang = getLanguageCode(versionIdOrLang);
  if (lang !== 'en' && BOOK_ABBREV_TRANSLATIONS[lang] && BOOK_ABBREV_TRANSLATIONS[lang][bookNumber]) {
    return BOOK_ABBREV_TRANSLATIONS[lang][bookNumber];
  }
  return BOOK_ABBREVIATIONS[bookNumber] || `Bk${bookNumber}`;
}
